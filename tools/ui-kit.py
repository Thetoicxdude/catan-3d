# The thin ornamental borders and dividers of the clean interface (src/ui/theme2.css), made from
# Kenney's "Fantasy UI Borders" (CC0, www.kenney.nl; the sprites used are in tools/art/kenney-ui):
# white sprites tinted to the interface's gold and written into src/ui/kit.css as data URIs, so the
# page needs no asset pack for them (the claude.ai page has none).
#   python3 tools/ui-kit.py
import base64, io, os
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'art', 'kenney-ui')
OUT = os.path.join(HERE, '..', 'src', 'ui', 'kit.css')

def tinted(name, rgb, alpha=1.0, mirror=False):
    im = Image.open(os.path.join(SRC, name)).convert('RGBA')
    if mirror:
        im = ImageOps.mirror(im)
    a = im.split()[3].point(lambda v: int(v * alpha))
    out = Image.new('RGBA', im.size, rgb + (255,))
    out.putalpha(a)
    buf = io.BytesIO()
    out.save(buf, 'PNG', optimize=True)
    return 'url(data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode() + ')'

GOLD = (226, 199, 135)
DIM = (176, 150, 98)
RED = (232, 120, 100)
rules = {
    # panels: a thin line with small meander corners (slice 24 of 96: 12 px at 2x)
    '--k-panel': tinted('panel-border-011.png', GOLD, 0.62),
    '--k-panel-hi': tinted('panel-border-011.png', GOLD, 0.95),
    '--k-panel-red': tinted('panel-border-011.png', RED, 0.9),
    # dialogs: larger corners (slice 32 of 96: 16 px at 2x)
    '--k-modal': tinted('panel-border-027.png', GOLD, 0.8),
    # small frames (cards of the menus, rows): plain corners
    '--k-plain': tinted('panel-border-012.png', DIM, 0.55),
    # section dividers: a line that fades out, its ornament towards the title
    '--k-div-r': tinted('divider-fade-004.png', GOLD, 0.85),
    '--k-div-l': tinted('divider-fade-004.png', GOLD, 0.85, mirror=True),
    '--k-rule': tinted('divider-fade-002.png', GOLD, 0.6),
}
css = ['/* generated by tools/ui-kit.py from Kenney "Fantasy UI Borders" (CC0, www.kenney.nl): do not edit */', ':root {']
css += [f'  {k}: {v};' for k, v in rules.items()]
css += ['}', '']
open(OUT, 'w').write('\n'.join(css))
print('wrote', os.path.normpath(OUT), sum(len(v) for v in rules.values()), 'bytes of images')

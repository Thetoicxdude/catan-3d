# The pictures of the map-table interface (src/ui/theme3.css), written into src/ui/kit3.css as data URIs
# so the page needs no asset pack for them (the claude.ai page has none).
#
# Only pictures that are used whole, at or below their own size: shapes for masks (the wax seal, the
# hexagon, a swallow-tailed pennant), ink drawings, two ink flourishes and a medal. The surfaces of the
# interface (paper, wood, cloth) are plain colours in theme3.css: a texture would have to be tiled,
# sliced or stretched to fit a panel, and that shows its seams.
#
# Sources (tools/art/kenney-ui3, all CC0, www.kenney.nl; SOURCES.txt there says which pack each file is
# from): the ink drawings of the "Cartography Pack", the seal and hexagon shapes of "UI Pack -
# Adventure", a flourish of "Fantasy UI Borders", a medal of "Medals". The pennant is drawn here.
#   python3 tools/ui-kit3.py
import base64, io, os
from PIL import Image, ImageOps, ImageFilter, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'art', 'kenney-ui3')
OUT = os.path.join(HERE, '..', 'src', 'ui', 'kit3.css')


def uri(im):
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return 'url(data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode() + ')'


def src(name):
    return Image.open(os.path.join(SRC, name))


def alpha_of(im):
    return im.convert('RGBA').split()[3]


def tint(name, rgb, alpha=1.0):
    """a line drawing or a white sprite in one colour, its own transparency kept"""
    a = alpha_of(src(name))
    if alpha != 1.0:
        a = a.point(lambda v: int(v * alpha))
    out = Image.new('RGBA', a.size, rgb + (255,))
    out.putalpha(a)
    return out


def white(a):
    out = Image.new('RGBA', a.size, (255, 255, 255, 255))
    out.putalpha(a)
    return out


rules = {}

# ── shapes used as masks (white where the shape is): the wax seal, the hexagon, a swallow-tailed pennant ──
rules['--u3-seal-mask'] = uri(white(alpha_of(src('round_damaged_brown.png'))))
rules['--u3-hex-mask'] = uri(white(alpha_of(src('hexagon_brown.png'))))
pen = Image.new('L', (64, 96), 0)
ImageDraw.Draw(pen).polygon([(0, 0), (64, 0), (64, 96), (32, 74), (0, 96)], fill=255)
rules['--u3-pennant-mask'] = uri(white(pen.filter(ImageFilter.GaussianBlur(0.5))))

# ── ink drawings (dark brown ink), 128 px: each is also a mask, in red ink beside a dialog's title ──
INK = (58, 36, 20)
for n in ['compass', 'chest', 'ship', 'castle', 'flag', 'banner', 'elementShield', 'lighthouse', 'mill',
          'towerWatch', 'rocksMountain', 'mine', 'waterWheel', 'gate']:
    rules[f'--u3-ink-{n}'] = uri(tint(n + '.png', INK, 0.9))

# ── the flourishes either side of a heading ──
rules['--u3-div-ink'] = uri(tint('divider-fade-000.png', INK, 0.85))
rules['--u3-div-ink-l'] = uri(ImageOps.mirror(tint('divider-fade-000.png', INK, 0.85)))


# ── a medal for the awards (longest road, largest army): Kenney's medal with its disc in brass and its
#    ribbon in crimson with a gilt stripe ──
def medal():
    im = src('shaded_medal3.png').convert('RGBA')
    out = Image.new('RGBA', im.size)
    pi, po = im.load(), out.load()
    crimson = [(0, (40, 6, 5)), (110, (98, 18, 14)), (180, (150, 34, 24)), (255, (190, 62, 44))]
    gilt = [(0, (90, 60, 20)), (160, (200, 160, 80)), (230, (240, 214, 150)), (255, (255, 240, 200))]
    brass = [(0, (60, 36, 10)), (120, (150, 105, 40)), (190, (214, 168, 86)), (240, (246, 222, 150)), (255, (255, 244, 205))]

    def ramp(stops, v):
        for i in range(len(stops) - 1):
            a, ca = stops[i]
            b, cb = stops[i + 1]
            if a <= v <= b:
                t = (v - a) / max(1, b - a)
                return tuple(int(ca[k] + (cb[k] - ca[k]) * t) for k in range(3))
        return stops[-1][1]

    for y in range(im.size[1]):
        for x in range(im.size[0]):
            r, g, b, a = pi[x, y]
            if not a:
                continue
            lum = (r * 299 + g * 587 + b * 114) / 1000
            if y < 4 or y >= 40:  # the clasp and the disc
                c = ramp(brass, lum)
            elif r - max(g, b) > 25:  # the ribbon's red
                c = ramp(crimson, lum + (255 - lum) * 0.35)
            else:  # its white stripe
                c = ramp(gilt, lum)
            po[x, y] = c + (a,)
    return out


rules['--u3-medal'] = uri(medal())

css = ['/* generated by tools/ui-kit3.py (Kenney CC0 art): do not edit */', ':root {']
css += [f'  {k}: {v};' for k, v in rules.items()]
css += ['}', '']
open(OUT, 'w').write('\n'.join(css))
total = sum(len(v) for v in rules.values())
print('wrote', os.path.normpath(OUT), f'{total / 1024:.0f} KB of images in {len(rules)} variables')
